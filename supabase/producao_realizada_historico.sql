-- Executar no Supabase para registrar as alterações futuras de produção realizada.
CREATE TABLE IF NOT EXISTS public.producao_realizada_historico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producao_id bigint NOT NULL,
  acao text NOT NULL CHECK (acao IN ('criado', 'editado', 'excluido')),
  alteracoes jsonb NOT NULL DEFAULT '{}'::jsonb,
  responsavel_id uuid,
  responsavel_nome text,
  ocorrido_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS producao_realizada_historico_producao_idx
  ON public.producao_realizada_historico (producao_id, ocorrido_em, id);

ALTER TABLE public.producao_realizada_historico ENABLE ROW LEVEL SECURITY;
REVOKE INSERT, UPDATE, DELETE ON public.producao_realizada_historico FROM anon, authenticated;
DROP POLICY IF EXISTS "Ler histórico de produção realizada" ON public.producao_realizada_historico;
CREATE POLICY "Ler histórico de produção realizada"
  ON public.producao_realizada_historico FOR SELECT TO authenticated USING (true);
GRANT SELECT ON public.producao_realizada_historico TO authenticated;

-- Para os registros anteriores à instalação, só se conhece a criação: edições passadas
-- não podem ser recuperadas sem um histórico pré-existente.
INSERT INTO public.producao_realizada_historico
  (producao_id, acao, alteracoes, responsavel_id, responsavel_nome, ocorrido_em)
SELECT p.id, 'criado', to_jsonb(p), p.user_id,
  coalesce(profile.name, CASE WHEN p.importado_automaticamente THEN 'Sistema' ELSE 'Não identificado' END),
  coalesce(p.created_at, now())
FROM public.producao_realizada p
LEFT JOIN public.profiles profile ON profile.id = p.user_id
WHERE NOT EXISTS (
  SELECT 1 FROM public.producao_realizada_historico h
  WHERE h.producao_id = p.id AND h.acao = 'criado'
);

CREATE OR REPLACE FUNCTION public.registrar_historico_producao_realizada()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_changes jsonb;
  v_actor_id uuid;
  v_actor_name text;
  v_production public.producao_realizada%ROWTYPE;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_production := OLD;
    v_changes := to_jsonb(OLD);
  ELSIF TG_OP = 'INSERT' THEN
    v_production := NEW;
    v_changes := to_jsonb(NEW);
  ELSE
    v_production := NEW;
    SELECT jsonb_object_agg(key, jsonb_build_object('antes', to_jsonb(OLD) -> key, 'depois', value))
      INTO v_changes
    FROM jsonb_each(to_jsonb(NEW))
    WHERE to_jsonb(OLD) -> key IS DISTINCT FROM value;
    IF v_changes IS NULL THEN RETURN NEW; END IF;
  END IF;

  v_actor_id := coalesce(auth.uid(), CASE WHEN TG_OP = 'INSERT' THEN v_production.user_id END);
  SELECT name INTO v_actor_name FROM public.profiles WHERE id = v_actor_id;
  v_actor_name := coalesce(v_actor_name, auth.jwt() ->> 'email',
    CASE WHEN v_production.importado_automaticamente THEN 'Sistema' ELSE 'Não identificado' END);

  INSERT INTO public.producao_realizada_historico
    (producao_id, acao, alteracoes, responsavel_id, responsavel_nome, ocorrido_em)
  VALUES (v_production.id,
    CASE TG_OP WHEN 'INSERT' THEN 'criado' WHEN 'UPDATE' THEN 'editado' ELSE 'excluido' END,
    v_changes, v_actor_id, v_actor_name,
    CASE WHEN TG_OP = 'INSERT' THEN coalesce(v_production.created_at, now()) ELSE now() END);

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS producao_realizada_historico_trigger ON public.producao_realizada;
CREATE TRIGGER producao_realizada_historico_trigger
  AFTER INSERT OR UPDATE OR DELETE ON public.producao_realizada
  FOR EACH ROW EXECUTE FUNCTION public.registrar_historico_producao_realizada();
