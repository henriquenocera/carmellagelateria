-- Migra a lista manual para listas (cabeçalho) e materiais associados.
-- A estrutura anterior continha somente itens e será substituída.
DROP TABLE IF EXISTS public.lista_compras_manual CASCADE;

CREATE TABLE public.lista_compras_manual (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  criado_por TEXT,
  status TEXT NOT NULL DEFAULT 'Aberta' CHECK (status IN ('Aberta', 'Fechada')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.lista_compras_manual_itens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lista_id BIGINT NOT NULL REFERENCES public.lista_compras_manual(id) ON DELETE CASCADE,
  insumo_id UUID NOT NULL REFERENCES public.cadastro_insumos(id) ON DELETE RESTRICT,
  quantidade NUMERIC NOT NULL CHECK (quantidade > 0),
  comprado BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX lista_compras_manual_itens_lista_id_idx
  ON public.lista_compras_manual_itens (lista_id);

ALTER TABLE public.lista_compras_manual ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lista_compras_manual_itens ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Acesso autenticado às listas de compras manuais"
  ON public.lista_compras_manual FOR ALL TO authenticated
  USING (TRUE) WITH CHECK (TRUE);

CREATE POLICY "Acesso autenticado aos itens de compras manuais"
  ON public.lista_compras_manual_itens FOR ALL TO authenticated
  USING (TRUE) WITH CHECK (TRUE);
