CREATE TABLE IF NOT EXISTS public.transferencias_cubas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_transferencia DATE NOT NULL DEFAULT CURRENT_DATE,
  descricao TEXT NOT NULL DEFAULT 'Transf. de Cubas',
  destino TEXT CHECK (destino IN ('Loja Ahu', 'Loja Alto XV', 'Food Service', 'Descartado', 'Outro')),
  cubas_ids BIGINT[] NOT NULL DEFAULT '{}',
  status TEXT NOT NULL DEFAULT 'Pendente' CHECK (status IN ('Pendente', 'Concluída', 'Cancelada')),
  user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.transferencias_cubas
  ADD COLUMN IF NOT EXISTS cubas_ids BIGINT[] NOT NULL DEFAULT '{}';

ALTER TABLE public.transferencias_cubas
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'Pendente';

ALTER TABLE public.transferencias_cubas
  DROP CONSTRAINT IF EXISTS transferencias_cubas_status_check;

ALTER TABLE public.transferencias_cubas
  ADD CONSTRAINT transferencias_cubas_status_check
  CHECK (status IN ('Pendente', 'Concluída', 'Cancelada'));

ALTER TABLE public.transferencias_cubas
  ALTER COLUMN destino DROP NOT NULL;

ALTER TABLE public.producao_realizada
  ADD COLUMN IF NOT EXISTS transferencia_cubas_id BIGINT
  REFERENCES public.transferencias_cubas(id) ON DELETE SET NULL;

ALTER TABLE public.cardsahu
  ADD COLUMN IF NOT EXISTS transferencia_cubas_id BIGINT
  REFERENCES public.transferencias_cubas(id) ON DELETE SET NULL;

ALTER TABLE public.cardsaltoxv
  ADD COLUMN IF NOT EXISTS transferencia_cubas_id BIGINT
  REFERENCES public.transferencias_cubas(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS producao_realizada_transferencia_cubas_id_idx
  ON public.producao_realizada (transferencia_cubas_id);

CREATE INDEX IF NOT EXISTS cardsahu_transferencia_cubas_id_idx
  ON public.cardsahu (transferencia_cubas_id);

CREATE INDEX IF NOT EXISTS cardsaltoxv_transferencia_cubas_id_idx
  ON public.cardsaltoxv (transferencia_cubas_id);

