CREATE TABLE IF NOT EXISTS public.transferencias_cubas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_transferencia DATE NOT NULL DEFAULT CURRENT_DATE,
  descricao TEXT NOT NULL DEFAULT 'Transf. de Cubas',
  destino TEXT NOT NULL CHECK (destino IN ('Loja Ahu', 'Loja Alto XV', 'Food Service', 'Descartado', 'Outro')),
  user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.producao_realizada
  ADD COLUMN IF NOT EXISTS transferencia_cubas_id BIGINT
  REFERENCES public.transferencias_cubas(id) ON DELETE SET NULL;

ALTER TABLE public.cardsahu
  ADD COLUMN IF NOT EXISTS transferencia_cubas_id BIGINT
  REFERENCES public.transferencias_cubas(id) ON DELETE SET NULL;

ALTER TABLE public.cardsaltoxv
  ADD COLUMN IF NOT EXISTS transferencia_cubas_id BIGINT
  REFERENCES public.transferencias_cubas(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS producao_realizada_transferencia_cubas_id_idx
  ON public.producao_realizada (transferencia_cubas_id);

CREATE INDEX IF NOT EXISTS cardsahu_transferencia_cubas_id_idx
  ON public.cardsahu (transferencia_cubas_id);

CREATE INDEX IF NOT EXISTS cardsaltoxv_transferencia_cubas_id_idx
  ON public.cardsaltoxv (transferencia_cubas_id);

ALTER TABLE public.transferencias_cubas ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'transferencias_cubas'
      AND policyname = 'Acesso autenticado às transferências de cubas'
  ) THEN
    CREATE POLICY "Acesso autenticado às transferências de cubas"
      ON public.transferencias_cubas FOR ALL TO authenticated
      USING (TRUE) WITH CHECK (TRUE);
  END IF;
END;
$$;
