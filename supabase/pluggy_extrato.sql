-- 1. Conexões da Pluggy: qual conta da Pluggy corresponde a qual conta do escritório.
CREATE TABLE IF NOT EXISTS public.pluggy_conexoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id text NOT NULL,
  account_id text NOT NULL UNIQUE,
  conta text NOT NULL,            -- mesmo rótulo usado em lancamentos_financeiros.conta
  descricao text,                 -- nome/número da conta como a Pluggy mostra
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL
);

ALTER TABLE public.pluggy_conexoes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir leitura para usuários autenticados"
ON public.pluggy_conexoes FOR SELECT TO authenticated USING (true);

CREATE POLICY "Permitir inserção para usuários autenticados"
ON public.pluggy_conexoes FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Permitir atualização para usuários autenticados"
ON public.pluggy_conexoes FOR UPDATE TO authenticated USING (true) WITH CHECK (true);

CREATE POLICY "Permitir exclusão para usuários autenticados"
ON public.pluggy_conexoes FOR DELETE TO authenticated USING (true);

-- 2. Transações do extrato já lançadas ou conciliadas, para não duplicar numa nova busca.
--    Várias transações podem apontar para o mesmo lançamento (caso "Agrupado").
--    Se o lançamento for excluído, o vínculo some junto e a transação volta como "Não Encontrado".
DO $$
DECLARE
  id_type text;
BEGIN
  SELECT format_type(a.atttypid, a.atttypmod) INTO id_type
  FROM pg_attribute a
  WHERE a.attrelid = 'public.lancamentos_financeiros'::regclass
    AND a.attname = 'id'
    AND NOT a.attisdropped;

  EXECUTE format($f$
    CREATE TABLE IF NOT EXISTS public.extrato_transacoes_importadas (
      origem text NOT NULL,           -- 'pluggy'
      id_transacao text NOT NULL,
      lancamento_id %s NOT NULL REFERENCES public.lancamentos_financeiros(id) ON DELETE CASCADE,
      conta text,
      data date,
      valor numeric,
      created_at timestamp with time zone DEFAULT now() NOT NULL,
      user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
      PRIMARY KEY (origem, id_transacao)
    )
  $f$, id_type);

  -- A tabela do Inter nunca chegou a ser usada; remove só se estiver vazia.
  IF to_regclass('public.inter_extrato_transacoes') IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public.inter_extrato_transacoes) THEN
      DROP TABLE public.inter_extrato_transacoes;
    END IF;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS extrato_transacoes_importadas_lancamento_id_idx
  ON public.extrato_transacoes_importadas (lancamento_id);
CREATE INDEX IF NOT EXISTS extrato_transacoes_importadas_data_idx
  ON public.extrato_transacoes_importadas (data);

ALTER TABLE public.extrato_transacoes_importadas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir leitura para usuários autenticados"
ON public.extrato_transacoes_importadas FOR SELECT TO authenticated USING (true);

CREATE POLICY "Permitir inserção para usuários autenticados"
ON public.extrato_transacoes_importadas FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Permitir exclusão para usuários autenticados"
ON public.extrato_transacoes_importadas FOR DELETE TO authenticated USING (true);
